import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { translate } from '../../app/utils/i18n.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')

export async function run({ assert }) {
  const home = await readFile(path.join(root, 'app/pages/index.vue'), 'utf8')
  const app = await readFile(path.join(root, 'app/app.vue'), 'utf8')
  const topicsRoute = await readFile(path.join(root, 'server/api/topics.get.js'), 'utf8')

  assert.match(home, /data-testid="search-dropdown"/)
  assert.match(home, /data-testid="home-topic-feeds"/)
  assert.match(home, /v-for="feed in homeFeeds"/)
  assert.match(home, /`home-\$\{feed\.key\}-topics`/)
  assert.match(home, /const MAX_SEARCH_LENGTH = 160/)
  assert.match(home, /const MAX_COMPOSER_LENGTH = 8000/)
  assert.match(home, /:maxlength="MAX_COMPOSER_LENGTH"/)
  assert.match(home, /query\.length > MAX_COMPOSER_LENGTH/)
  assert.match(home, /data-testid="composer-create-page"/)
  assert.match(home, /lines > 2/)
  assert.match(home, /data-testid="`mcp-copy-\$\{service\.key\}`"/)
  assert.match(home, /key: 'chatgpt'/)
  assert.match(home, /key: 'claude'/)
  assert.match(home, /key: 'cursor'/)
  assert.match(home, /<UIcon :name="service\.iconName"/)
  assert.match(home, /iconName: 'i-simple-icons-openai'/)
  assert.match(home, /iconName: 'i-simple-icons-claude'/)
  assert.match(home, /iconName: 'i-simple-icons-cursor'/)
  assert.match(home, /data-testid="agent-guide-link"/)
  assert.match(home, /navigator\.clipboard\.writeText\(mcpInstruction\(service\)\)/)
  assert.match(home, /data-testid="mcp-copy-toast"/)
  assert.match(home, /fixed inset-x-4 top-20/)
  assert.match(home, /sm:top-24 sm:right-6/)
  assert.doesNotMatch(home, /data-testid="mcp-copy-toast"[^>]*bottom-5/)
  assert.doesNotMatch(home, /href="\/connect"/)
  assert.doesNotMatch(home, /href="\/api\.txt"/)
  assert.doesNotMatch(home, /href="\/openapi-v1\.yaml"/)
  assert.doesNotMatch(home, /href="\/llms\.txt"/)
  assert.match(home, /sort: 'hot'/)
  assert.match(home, /sort: 'best'/)
  assert.match(home, /sort: 'worst'/)
  assert.match(home, /home\.bestTopics/)
  assert.match(home, /home\.worstTopics/)
  assert.match(home, /includeTasks: false/)
  assert.match(topicsRoute, /const requestedSort = String\(query\.sort \|\| 'new'\)/)
  assert.match(topicsRoute, /\['new', 'hot', 'best', 'worst'\]\.includes\(requestedSort\)/)
  assert.match(topicsRoute, /const includeTasks = String\(query\.includeTasks \|\| 'true'\)/)
  assert.match(topicsRoute, /GREATEST\(score, 0\) \* 5/)
  assert.match(topicsRoute, /reply_count \* 8/)
  assert.match(topicsRoute, /LN\(1 \+ LEAST\(reads, 1000\)::numeric\) \* 3/)
  assert.match(topicsRoute, /EXP\(-GREATEST\(EXTRACT\(EPOCH FROM \(now\(\) - last_activity_at\)\)/)
  assert.match(topicsRoute, /result_type = 'topic' AND \(vote_count > 0 OR reply_count > 0\)/)
  assert.match(topicsRoute, /count\(\*\)::int AS vote_count/)
  assert.match(topicsRoute, /count\(\*\) FILTER \(WHERE value = -1\)::int AS downvotes/)
  assert.match(topicsRoute, /\$8 <> 'worst' OR score < 0/)
  assert.match(topicsRoute, /CASE WHEN \$8 = 'best' THEN score ELSE 0 END DESC/)
  assert.match(topicsRoute, /CASE WHEN \$8 = 'worst' THEN score ELSE 0 END ASC/)
  assert.match(home, /:aria-expanded="String\(searchOpen && Boolean\(search\.trim\(\)\)\)"/)
  assert.match(home, /q: debouncedSearch\.value, locale: locale\.value, limit: 6/)
  assert.match(home, /setTimeout\(\(\) => \{ debouncedSearch\.value = value\.trim\(\)\.slice\(0, MAX_SEARCH_LENGTH\) \}, 250\)/)
  assert.match(home, /data-testid="result-kind"/)
  assert.match(home, /item\.result_type === 'task'/)
  assert.match(home, /\/a\/\$\{encodeURIComponent\(item\.id\)\}/)
  assert.match(home, /\$fetch\('\/api\/article-drafts'/)
  assert.match(home, /data-testid="search-create-article"/)
  assert.match(home, /data-testid="search-create-article-guidance"/)
  assert.match(home, /role="button"/)
  assert.match(home, /hover:bg-white focus-visible:bg-white/)
  assert.match(home, /data-testid="search-create-loader"/)
  assert.match(home, /search-create-intent/)
  assert.match(home, /home\.askInAiki/)
  assert.match(home, /home\.discussInAiki/)
  assert.match(home, /if \(composerMode\.value \|\| !searchHasNoResults\.value\) return null/)
  assert.match(home, /requestedKind: requestedKind\.value/)
  assert.match(home, /response\.topic\?\.short_path/)
  assert.doesNotMatch(home, /startPaidArticle/)
  assert.doesNotMatch(home, /sessionStorage\.getItem\(orderStorageKey\)/)
  assert.match(home, /authState\.value\?\.actor/)
  assert.doesNotMatch(home, /refreshArticleOrder/)
  assert.doesNotMatch(home, /navigateTo\(`\/orders\/\$\{encodeURIComponent\(response\.order\.id\)\}`\)/)
  assert.match(home, /dark:bg-zinc-900/)
  assert.match(home, /dark:hover:bg-emerald-900\/30/)
  assert.match(app, /to: '\/tasks'/)

  assert.equal(translate('en', 'order.statusQueued'), 'Waiting for an agent')
  assert.equal(translate('ru', 'order.statusQueued'), 'Ожидает исполнителя')
  assert.equal(translate('en', 'order.statusSucceeded'), 'Draft ready for review')
  assert.equal(translate('ru', 'order.statusSucceeded'), 'Черновик готов к проверке')
  assert.equal(translate('en', 'home.hotTopics'), 'Hot topics')
  assert.equal(translate('ru', 'home.hotTopics'), 'Горячие темы')
  assert.equal(translate('ru', 'home.title'), 'Знания достоверны, когда каждый может проверить их вопросами.')
  assert.equal(translate('ru', 'home.discussInAiki'), 'Обсудить в AIKI')
  assert.equal(translate('ru', 'home.askInAiki'), 'Спросить в AIKI')
  assert.equal(translate('en', 'home.newTopics'), 'New topics')
  assert.equal(translate('ru', 'home.newTopics'), 'Новые темы')
  assert.equal(translate('en', 'home.bestTopics'), 'Best topics')
  assert.equal(translate('ru', 'home.bestTopics'), 'Лучшие темы')
  assert.equal(translate('en', 'home.worstTopics'), 'Worst topics')
  assert.equal(translate('ru', 'home.worstTopics'), 'Худшие темы')
  assert.equal(translate('en', 'home.mcpCopied'), 'Instruction copied. Paste it into your app chat window.')
  assert.equal(translate('ru', 'home.mcpCopied'), 'Инструкция скопирована. Вставьте её в окно чата вашего приложения.')
  assert.equal(translate('en', 'tasks.openTaskList'), 'Open writing task')
  assert.equal(translate('ru', 'tasks.openTaskList'), 'Открыть задачу')
  assert.match(translate('en', 'order.duplicateHint'), /matching page exists/)
  assert.match(translate('ru', 'order.duplicateHint'), /подходящей страницы нет/)
}
