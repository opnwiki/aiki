import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { translate } from '../../app/utils/i18n.js'
import { formatCount } from '../../app/utils/number-format.js'
import { bugReportUrl, featureProposalUrl, sourceRepository } from '../../app/utils/source.js'
import { SOURCE_REPOSITORY, normalizeDisplayName, presentWebManifest, publicNodeProfile, readBrandFavicon, readBrandIcon, sanitizeSvg } from '../../server/utils/node-profile.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')

export async function run({ assert }) {
  const open = publicNodeProfile({ domain: 'aiki.wiki', countsPublic: true, pages: 3, users: 1, agents: 4, online24h: 7, contactUrl: 'https://node.example/contact' })
  assert.equal(open.countsPublic, true)
  assert.equal(open.pages, 3)
  assert.equal(open.users, 1)
  assert.equal(open.agents, 4)
  assert.equal(open.online24h, 7)
  assert.equal(open.repository, 'https://github.com/opnwiki/aiki')
  assert.equal(open.contactUrl, 'https://node.example/contact')
  assert.deepEqual(open.federation, { enabled: false, mode: 'paused' })
  assert.deepEqual(publicNodeProfile({ domain: 'aiki.wiki', federationEnabled: true, federationMode: 'open' }).federation, { enabled: true, mode: 'open' })
  assert.equal(sourceRepository, SOURCE_REPOSITORY)
  assert.equal(bugReportUrl, 'https://github.com/opnwiki/aiki/issues/new?template=bug_report.yml')
  assert.equal(featureProposalUrl, 'https://github.com/opnwiki/aiki/issues/new?template=feature_proposal.yml')
  assert.equal(translate('en', 'footer.source'), 'Source code')
  assert.equal(translate('ru', 'footer.source'), 'Исходный код')
  assert.equal(translate('ru', 'admin.bugReport'), 'Баг-репорт')
  assert.equal(translate('zh', 'footer.source'), 'Source code')
  assert.equal(open.displayName, 'AiKi')
  assert.equal(open.iconUrl, null)
  assert.equal(open.faviconUrl, null)
  assert.equal(open.accentLight, '#3d5c4e')
  assert.equal(open.accentDark, '#8aa899')
  assert.equal(open.registrationOpen, true)
  assert.equal(open.moderationMode, 'community')
  assert.equal(publicNodeProfile({ domain: 'aiki.wiki', countsPublic: true, pages: 1, users: 1, moderationMode: 'manual' }).moderationMode, 'manual')
  assert.equal(open.version, '1.2.11')
  assert.equal(formatCount(11674), '11,674')
  assert.equal(formatCount(1000000), '1,000,000')
  assert.equal(formatCount(null), '0')
  assert.equal(publicNodeProfile({ domain: 'aiki.wiki', countsPublic: true, pages: 1, users: 1, registrationOpen: false }).registrationOpen, false)
  const named = publicNodeProfile({ domain: 'aiki.wiki', countsPublic: true, pages: 1, users: 1, displayName: '  Узел ', iconVersion: 'abc', faviconVersion: 'def' })
  assert.equal(named.displayName, 'Узел')
  assert.equal(named.iconUrl, '/api/node-icon?v=abc')
  assert.equal(named.faviconUrl, '/api/node-favicon?v=def')
  assert.equal(normalizeDisplayName('   ').value, null)
  assert.equal(normalizeDisplayName('x'.repeat(41)).ok, false)
  const png = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg=='
  assert.equal(readBrandIcon(png).value.type, 'image/png')
  assert.equal(readBrandFavicon(png).value.type, 'image/png')
  assert.equal(readBrandIcon('data:image/svg+xml;base64,PHN2Zy8+').ok, false)
  const svg = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 8 8"><rect width="8" height="8" fill="#12352a"/></svg>').toString('base64')
  assert.equal(readBrandIcon(`data:image/svg+xml;base64,${svg}`).value.type, 'image/svg+xml')
  assert.equal(readBrandFavicon(`data:image/svg+xml;base64,${svg}`).ok, false)
  const scripted = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"><script>alert(1)</script></svg>').toString('base64')
  assert.equal(readBrandIcon(`data:image/svg+xml;base64,${scripted}`).ok, false)
  assert.equal(sanitizeSvg('<svg onload="alert(1)"></svg>'), null)
  const manifest = presentWebManifest({ name: 'AIKI', icons: [{ src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' }] }, { faviconVersion: 'abc', faviconType: 'image/png' })
  assert.equal(manifest.icons[0].src, '/api/node-favicon?v=abc')
  assert.equal(manifest.icons[1].purpose, 'maskable')
  assert.equal(presentWebManifest({ icons: [{ src: '/icon-192.png' }] }, {}).icons[0].src, '/icon-192.png')

  const hidden = publicNodeProfile({ domain: 'aiki.wiki', countsPublic: false, pages: 3, users: 1 })
  assert.equal(hidden.countsPublic, false)
  assert.equal(hidden.pages, null)
  assert.equal(hidden.users, null)
  assert.equal(hidden.agents, null)
  assert.equal(publicNodeProfile({ domain: 'local.test', countsPublic: 'true', pages: 9, users: 4 }).pages, null)

  const page = await readFile(path.join(root, 'app/pages/node.vue'), 'utf8')
  const shell = await readFile(path.join(root, 'app/app.vue'), 'utf8')
  const admin = await readFile(path.join(root, 'app/pages/admin.vue'), 'utf8')
  const login = await readFile(path.join(root, 'app/pages/login.vue'), 'utf8')
  const api = await readFile(path.join(root, 'server/api/node.get.js'), 'utf8')
  const activityMiddleware = await readFile(path.join(root, 'server/middleware/site-activity.js'), 'utf8')
  const patch = await readFile(path.join(root, 'server/api/admin/settings.patch.js'), 'utf8')
  assert.match(page, /data-testid="node-counts"/)
  assert.match(page, /formatCount\(pages\)/)
  assert.match(admin, /formatCount\(card\.value\)/)
  assert.match(page, /data-testid="node-version"/)
  assert.match(admin, /data-testid="admin-update"/)
  assert.match(admin, /data-testid="admin-bug-report"/)
  assert.match(admin, /data-testid="admin-feature-proposal"/)
  assert.match(shell, /data-testid="footer-source"/)
  assert.match(shell, /data-testid="footer-online"/)
  assert.match(shell, /footer\.serverVersion/)
  assert.match(page, /data-testid="node-counts-hidden"/)
  assert.match(page, /data-testid="node-publisher-contact"/)
  assert.match(page, /docker compose up --build -d/)
  assert.match(admin, /data-testid="counts-public-toggle"/)
  assert.match(admin, /data-testid="registration-open-toggle"/)
  assert.match(login, /data-testid="registration-closed"/)
  assert.match(login, /data-testid="auth-create"/)
  assert.match(patch, /registrationOpen must be true or false/)
  assert.match(admin, /data-testid="node-display-name"/)
  assert.match(admin, /data-testid="node-icon-file"/)
  assert.match(admin, /data-testid="node-favicon-file"/)
  assert.match(admin, /image\/svg\+xml/)
  assert.match(shell, /data-testid="brand-name"/)
  assert.match(admin, /method: 'PATCH'/)
  assert.match(api, /publicNodeProfile/)
  assert.match(api, /faviconVersion: facts.faviconVersion/)
  assert.match(api, /contactUrl: config\.public\.publisherContactUrl/)
  assert.match(api, /loadOnlineVisitors/)
  assert.match(activityMiddleware, /recordSiteActivity/)
  assert.match(activityMiddleware, /path === '\/mcp' && event\.method === 'POST'/)
  assert.match(patch, /typeof input\?\.countsPublic !== 'boolean'/)
  assert.match(patch, /requireNodeAdmin/)
  assert.equal(translate('ru', 'node.usersLabel'), 'Учётные записи')
  assert.equal(translate('ru', 'node.humansLabel'), 'Люди')
  assert.equal(translate('ru', 'node.agentsLabel'), 'Агенты')
  assert.equal(translate('ru', 'admin.brandTitle'), 'Название и иконка')
  assert.equal(translate('ru', 'admin.faviconTitle'), 'Фавикон и иконка приложения')
  assert.equal(translate('zh', 'admin.faviconTitle'), 'Favicon and app icon')
  assert.equal(translate('en', 'admin.iconLabel'), 'Header mark')
  assert.equal(translate('ru', 'footer.online24h'), 'онлайн за 24 часа')
  assert.equal(translate('en', 'footer.developerResources'), 'Connect an agent')
  assert.equal(translate('ru', 'footer.developerResources'), 'Подключить агента')
  assert.equal(translate('en', 'footer.serverVersion', { version: '1.2.11' }), 'Server version 1.2.11')
  assert.equal(translate('ru', 'admin.registrationLabel'), 'Регистрация новых аккаунтов')
  assert.equal(translate('ru', 'auth.registrationClosed'), 'Регистрация на этом узле закрыта. Войти можно в уже созданный аккаунт.')
  assert.equal(translate('en', 'admin.namePlaceholder'), 'AiKi')
  assert.equal(translate('en', 'node.countsHidden'), 'The operator of this node has chosen not to publish how many pages and accounts it has.')
}
